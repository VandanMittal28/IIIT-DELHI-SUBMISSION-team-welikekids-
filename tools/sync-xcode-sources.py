#!/usr/bin/env python3
"""Register any Swift file in ios/Sidequest/ that the Xcode project doesn't know about yet.

The project is generated by XcodeGen from ios/project.yml, but the generated
ios/Sidequest.xcodeproj is committed and XcodeGen is not installed on every machine. Files
added to the source directory are therefore invisible to the build until they appear in the
pbxproj. This script closes that gap without needing XcodeGen.

It only ever adds; it never removes or reorders existing entries. Object IDs are derived from
the file name so re-running is idempotent and produces no diff once a file is registered.

Usage: python3 tools/sync-xcode-sources.py [--check]
       --check exits non-zero if anything is missing, without writing.
"""

from __future__ import annotations

import hashlib
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "ios" / "Sidequest"
PBXPROJ = ROOT / "ios" / "Sidequest.xcodeproj" / "project.pbxproj"


def object_id(name: str, salt: str) -> str:
    """A stable 24-character uppercase hex ID, the shape Xcode uses."""
    return hashlib.md5(f"{salt}:{name}".encode()).hexdigest()[:24].upper()


def insert_sorted(text: str, section_start: str, section_end: str, line: str, sort_key: str) -> str:
    """Insert `line` into a pbxproj section, keeping the section's existing sort order."""
    start = text.index(section_start) + len(section_start)
    end = text.index(section_end, start)
    body = text[start:end]
    entries = [entry for entry in body.split("\n") if entry.strip()]
    for index, entry in enumerate(entries):
        existing = re.search(r"/\* ([^*]+?) (?:in |\*/)", entry)
        if existing and existing.group(1).lower() > sort_key.lower():
            entries.insert(index, line)
            break
    else:
        entries.append(line)
    return text[:start] + "\n" + "\n".join(entries) + "\n" + text[end:]


def main() -> int:
    check_only = "--check" in sys.argv
    text = PBXPROJ.read_text()

    sources = sorted(path.name for path in SRC_DIR.glob("*.swift"))
    missing = [name for name in sources if f"/* {name} */" not in text]

    if not missing:
        print(f"xcode sources in sync ({len(sources)} Swift files)")
        return 0

    if check_only:
        print("missing from Sidequest.xcodeproj: " + ", ".join(missing))
        return 1

    for name in missing:
        file_ref = object_id(name, "fileRef")
        build_file = object_id(name, "buildFile")

        text = insert_sorted(
            text,
            "/* Begin PBXBuildFile section */\n",
            "/* End PBXBuildFile section */",
            f"\t\t{build_file} /* {name} in Sources */ = {{isa = PBXBuildFile; fileRef = {file_ref} /* {name} */; }};",
            name,
        )
        text = insert_sorted(
            text,
            "/* Begin PBXFileReference section */\n",
            "/* End PBXFileReference section */",
            f"\t\t{file_ref} /* {name} */ = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = {name}; sourceTree = \"<group>\"; }};",
            name,
        )

        # The group that lists the app's files, and the app target's compile phase.
        group_anchor = "\t\t\t\t82807BCAE15EBB71B83165AB /* SidequestApp.swift */,\n"
        text = text.replace(group_anchor, group_anchor + f"\t\t\t\t{file_ref} /* {name} */,\n", 1)

        phase_anchor = "\t\t\t\tE936C14785F40CA78899EC1D /* SidequestApp.swift in Sources */,\n"
        text = text.replace(phase_anchor, phase_anchor + f"\t\t\t\t{build_file} /* {name} in Sources */,\n", 1)

        print(f"added {name}")

    PBXPROJ.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
